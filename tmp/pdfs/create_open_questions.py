def num(value):
    return str(value).translate(str.maketrans('0123456789', '٠١٢٣٤٥٦٧٨٩'))

def visual(text):
    return get_display(arabic_reshaper.reshape(text), base_dir='R')

def draw(c, text, x, y, size=12, bold=False, color=INK):
    c.setFont('ArabicBold' if bold else 'Arabic', size)
    c.setFillColor(HexColor(color))
    c.drawRightString(x, y, visual(text))

def wrap(text, width, size=12, font='Arabic'):
    lines, current = [], ''
    for word in text.split():
        candidate = (current + ' ' + word).strip()
        if current and pdfmetrics.stringWidth(visual(candidate), font, size) > width:
            lines.append(current)
            current = word
        else:
            current = candidate
    if current:
        lines.append(current)
    return lines

def paragraph(c, text, y, size=12, leading=18, color=INK):
    for item in wrap(text, WIDTH, size):
        draw(c, item, RIGHT, y, size, color=color)
        y -= leading
    return y

